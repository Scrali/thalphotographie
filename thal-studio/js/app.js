function hours(a,b){
  if(!a || !b || !a.includes(':') || !b.includes(':')) return 0;
  let [ah,am]=a.split(':').map(Number),[bh,bm]=b.split(':').map(Number);
  let x=ah+am/60,y=bh+bm/60;
  if(!Number.isFinite(x) || !Number.isFinite(y)) return 0;
  if(y<x)y+=24;
  return y-x;
}
