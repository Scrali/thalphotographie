# THAL Studio V2.1 — sauvegarde des devis

## Nouveautés

- Couleur dédiée pour les libellés/champs du devis :
  `Couleur libellés / champs`.
- Bouton `Enregistrer le devis`.
- Sauvegarde serveur dans :
  `data/quotes/`
- Page `Mes devis` fonctionnelle.
- Réouverture d’un devis sauvegardé.
- Export PDF avec nom basé sur :
  `NuméroDevis_Client`.

## Installation

1. Remplace le dossier `thal-studio` par cette version.
2. Commit / push.
3. OVH → Déployer Git.
4. Ouvre THAL Studio.
5. Teste :
   - Nouveau devis,
   - Enregistrer le devis,
   - Mes devis,
   - Ouvrir.

## Important

Si tu as déjà un mot de passe personnel, vérifie ton fichier d’authentification après remplacement.
